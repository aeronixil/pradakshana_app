English meaning

Opening prayer

With the dust of my teacher’s lotus feet, I cleanse the mirror of my mind. I describe the pure glory of Rama, who grants the four aims of life: righteousness, prosperity, fulfillment and liberation.

Knowing the limits of my understanding, I remember you, son of the wind. Grant me strength, wisdom and learning; remove my suffering and faults.

The forty verses

1. Glory to Hanuman, an ocean of wisdom and virtue. Glory to the lord of the vanaras, whose fame shines through the three worlds.

2. You are Rama’s messenger, the abode of incomparable strength. You are Anjana’s son, known also as the son of the wind.

3. Great hero, mighty and brave, with a body strong as a thunderbolt: you dispel harmful thoughts and stand beside good judgment.

4. Your golden form is beautifully adorned. Earrings grace your ears, and your hair falls in curls.

5. A thunderbolt and a banner shine in your hands. A sacred thread of munja grass rests upon your shoulder.

6. Born of Shankara’s power and the delight of Kesari, your radiance and greatness are honored throughout the world.

7. Learned, virtuous and deeply discerning, you are always eager to carry out Rama’s work.

8. You delight in hearing the deeds of your Lord. Rama, Lakshmana and Sita dwell within your heart.

9. Taking a tiny form, you appeared before Sita. Taking a fearsome form, you set Lanka ablaze.

10. Taking a mighty form, you overcame the demons and accomplished Rama’s tasks.

11. You brought the life-restoring herb and revived Lakshmana. Rama joyfully clasped you to his heart.

12. Rama praised you greatly: “You are as dear to me as my brother Bharata.”

13. “May a thousand mouths sing your glory,” said the Lord, embracing you.

14–15. Sages such as Sanaka, Brahma and the great seers; Narada, Saraswati and Shesha; Yama, Kubera and the guardians of the directions—even poets and scholars cannot fully describe your glory.

16. You helped Sugriva by bringing him to Rama, through whom he regained his kingdom.

17. Vibhishana followed your counsel and became the ruler of Lanka, as the whole world knows.

18. Seeing the sun far away, you took it for a sweet fruit and flew to swallow it.

19. Carrying the Lord’s ring in your mouth, you crossed the ocean. Such a feat was no wonder for you.

20. All the difficult tasks of this world become easy through your grace.

21. You guard Rama’s doorway; none may enter without your permission.

22. All who take refuge in you find happiness. With you as protector, there is nothing to fear.

23. You alone can contain your own immense power. Your mighty call makes the three worlds tremble.

24. Spirits and harmful beings do not draw near when your name, great hero, is spoken.

25. The hymn praises you, brave Hanuman, as the remover of illness and pain for those who continually remember your name.

26. You free from trouble those who keep their thoughts, actions and words devoted to you.

27. Rama, the ascetic king, reigns supreme. You fulfill all his purposes.

28. Whoever brings a heartfelt wish to you receives the abundant fruits of life.

29. Your glory endures through all four ages. Your renown illuminates the world.

30. You protect saints and seekers, destroy evil, and are beloved of Rama.

31. Mother Janaki blessed you with the power to bestow the eight spiritual attainments and nine treasures.

32. You hold the nectar of devotion to Rama and remain forever his devoted servant.

33. Through devotion to you, one reaches Rama and is freed from the sorrows of lifetime after lifetime.

34. At life’s end, one goes to Rama’s abode; if born again, one is known as a devotee of the Lord.

35. Even without directing the mind to other deities, serving Hanuman brings every happiness.

36. Troubles fall away and suffering is eased for those who remember mighty Hanuman.

37. Glory, glory, glory to you, Lord Hanuman. Show me the kindness of a revered teacher.

38. Whoever recites this prayer a hundred times is released from bondage and receives great joy.

39. Whoever reads this Hanuman Chalisa attains fulfillment; Shiva bears witness to this.

40. Tulsidas is forever the Lord’s servant. O Lord, make your dwelling in my heart.

Closing prayer

Son of the wind, remover of trouble, embodiment of auspiciousness: dwell in my heart together with Rama, Lakshmana and Sita, O lord of the divine ones.

Glory to Rama, beloved of Sita.''';
